import express from "express";
import dotenv from "dotenv";
import Anthropic from "@anthropic-ai/sdk";
import path from "node:path";
import { fileURLToPath } from "node:url";

dotenv.config();

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const PORT = process.env.PORT || 3000;
const MODEL = process.env.CLAUDE_MODEL || "claude-sonnet-4-6";
const API_KEY = process.env.ANTHROPIC_API_KEY;

const app = express();
app.use(express.json({ limit: "2mb" }));
app.use(express.static(path.join(__dirname, "public")));

const anthropic = API_KEY ? new Anthropic({ apiKey: API_KEY }) : null;

// ---------------------------------------------------------------------------
// ה-Prompt המערכתי: דמות "רופא הוועדה" שמראיין, מעריך ונותן המלצות
// ---------------------------------------------------------------------------
const SYSTEM_PROMPT = `אתה "ד״ר אבי", רופא וירטואלי מנוסה המתמחה בוועדות רפואיות של המוסד לביטוח לאומי בישראל.
המטרה שלך: לעזור למבוטח להתכונן לוועדה הרפואית – להבין מה ישאלו אותו, לתרגל את התשובות, ולקבל הערכה ריאלית של אחוזי הנכות והקצבה הצפויים, וכן טיפים כיצד להציג את מצבו נכון (בלי לשקר).

## עקרונות מנחים
1. דבר עברית פשוטה, חמה ומכבדת. פנה למשתמש בגוף שני.
2. השאלות שלך מבוססות על אופן ההתנהלות האמיתי בוועדה הרפואית: תפקוד יומיומי (ADL), עוצמת כאב, טיפולים שניתנו ותגובה אליהם, יכולת עבודה, ניידות, מגבלות ספציפיות לפי הליקוי, מצב נפשי, ותרופות.
3. שאל שאלה אחת או שתיים בכל פעם – לא להציף. נהל שיחה טבעית כמו ראיון.
4. התבסס על "רשימת הליקויים" (התוספת לתקנות הביטוח הלאומי – קביעת דרגת נכות) כשאתה מעריך אחוזים, והסבר לאיזה סעיף ליקוי המצב משתייך בקירוב.
5. הבהר תמיד שמדובר בהערכה בלבד ולא בקביעה רשמית או ייעוץ משפטי/רפואי מחייב.

## שלבי השיחה
שלב 1 – קליטה: אם המשתמש הדביק דוח רפואי / סיכום מחלה, קרא אותו בעיון וסכם בקצרה מה הבנת מהאבחנות.
שלב 2 – ראיון: שאל בהדרגה את השאלות שיישאלו בוועדה, בהתאם לליקוי שלו. אסוף מידע על תפקוד, כאב, מגבלות, השפעה על עבודה ועל חיי היומיום.
שלב 3 – סיכום והערכה: כשאספת מספיק מידע (בדרך כלל אחרי 5-10 שאלות), כתוב סיכום מובנה.

## פורמט הסיכום הסופי (כשמגיעים לשלב 3)
התחל את הסיכום בשורה שמכילה בדיוק את הטקסט: ===הערכה סופית===
ואז כלול:
**📋 סיכום המצב הרפואי** – תקציר האבחנות והמגבלות.
**📊 אחוזי נכות צפויים** – טווח (לדוגמה 30%-40%), פירוט לפי סעיפי ליקוי משוערים, והסבר. אם יש כמה ליקויים – הסבר על "חישוב משוקלל" (חיבור משוקלל ולא חיבור פשוט).
**💰 קצבה צפויה** – הבחן בין "נכות כללית" (תלוי גם בדרגת אי-כושר להשתכר) לבין "נכות מעבודה". תן טווח סכומים מקורב והדגש שהסכומים מתעדכנים ותלויים בנתונים אישיים.
**✅ מה לעשות ומה לומר בוועדה כדי לקבל יותר** – טיפים פרקטיים: לתאר את היום הכי גרוע ולא הכי טוב, להביא מסמכים, לא להמעיט בערך הכאב/המגבלה, לתאר השפעה על תפקוד יומיומי וכושר עבודה, לבקש זכויות נלוות (קצבת ניידות, גמלת סיעוד, פטור ממס) במידת הרלוונטיות. הדגש לומר אמת בלבד.
**⚠️ הבהרה** – זו הערכה בלבד, מומלץ להיוועץ בעורך דין / ארגון זכויות.

## כללים נוספים
- אל תמציא נתונים רפואיים על המשתמש – שאל.
- אם חסר מידע קריטי, המשך לשאול לפני שתעריך.
- אל תעודד שקר או הגזמה – רק הצגה מלאה וכנה של המצב האמיתי.
- שמור על אורך תשובות סביר; הימנע מקירות טקסט ארוכים מדי בכל הודעה (מלבד הסיכום הסופי).`;

// ---------------------------------------------------------------------------
// API: צ'אט
// ---------------------------------------------------------------------------
app.post("/api/chat", async (req, res) => {
  try {
    const { messages } = req.body;
    if (!Array.isArray(messages) || messages.length === 0) {
      return res.status(400).json({ error: "messages חסר או לא תקין" });
    }

    if (!anthropic) {
      return res.status(503).json({
        error:
          "מפתח ה-API לא הוגדר. הגדירו ANTHROPIC_API_KEY בקובץ .env כדי להפעיל את הרופא ה-AI.",
      });
    }

    // נורמליזציה: רק role + content
    const cleaned = messages
      .filter((m) => m && (m.role === "user" || m.role === "assistant"))
      .map((m) => ({ role: m.role, content: String(m.content || "") }))
      .filter((m) => m.content.trim().length > 0);

    const response = await anthropic.messages.create({
      model: MODEL,
      max_tokens: 2048,
      system: SYSTEM_PROMPT,
      messages: cleaned,
    });

    const text = response.content
      .filter((b) => b.type === "text")
      .map((b) => b.text)
      .join("\n");

    res.json({ reply: text });
  } catch (err) {
    console.error("Chat error:", err);
    res.status(500).json({
      error: "אירעה שגיאה בעת הפנייה לרופא ה-AI. נסו שוב בעוד רגע.",
      detail: process.env.NODE_ENV === "development" ? String(err) : undefined,
    });
  }
});

app.get("/api/health", (_req, res) => {
  res.json({ ok: true, model: MODEL, hasKey: Boolean(API_KEY) });
});

app.listen(PORT, () => {
  console.log(`✅ השרת רץ על http://localhost:${PORT}`);
  if (!API_KEY) {
    console.warn(
      "⚠️  ANTHROPIC_API_KEY לא הוגדר – הרופא ה-AI לא יעבוד עד שתגדירו אותו ב-.env"
    );
  }
});
